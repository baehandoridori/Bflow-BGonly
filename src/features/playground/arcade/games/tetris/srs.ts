import type { TetrisPiece, TetrisRotation } from './types.ts';

// SRS 킥 테이블 — 이미 y-down 좌표로 변환된 값(표준 SRS의 +y↑를 반전). 계획서 §Task 11 표가 정본.
// 키는 `${from}>${to}` (0=spawn,1=R,2=2,3=L). 순서대로 5개 오프셋을 시도, 전부 실패면 회전 취소.
type Kick = readonly (readonly [number, number])[];

const JLSTZ_KICKS: Record<string, Kick> = {
  '0>1': [[0, 0], [-1, 0], [-1, -1], [0, 2], [-1, 2]],
  '1>0': [[0, 0], [1, 0], [1, 1], [0, -2], [1, -2]],
  '1>2': [[0, 0], [1, 0], [1, 1], [0, -2], [1, -2]],
  '2>1': [[0, 0], [-1, 0], [-1, -1], [0, 2], [-1, 2]],
  '2>3': [[0, 0], [1, 0], [1, -1], [0, 2], [1, 2]],
  '3>2': [[0, 0], [-1, 0], [-1, 1], [0, -2], [-1, -2]],
  '3>0': [[0, 0], [-1, 0], [-1, 1], [0, -2], [-1, -2]],
  '0>3': [[0, 0], [1, 0], [1, -1], [0, 2], [1, 2]],
};

const I_KICKS: Record<string, Kick> = {
  '0>1': [[0, 0], [-2, 0], [1, 0], [-2, 1], [1, -2]],
  '1>0': [[0, 0], [2, 0], [-1, 0], [2, -1], [-1, 2]],
  '1>2': [[0, 0], [-1, 0], [2, 0], [-1, -2], [2, 1]],
  '2>1': [[0, 0], [1, 0], [-2, 0], [1, 2], [-2, -1]],
  '2>3': [[0, 0], [2, 0], [-1, 0], [2, -1], [-1, 2]],
  '3>2': [[0, 0], [-2, 0], [1, 0], [-2, 1], [1, -2]],
  '3>0': [[0, 0], [1, 0], [-2, 0], [1, 2], [-2, -1]],
  '0>3': [[0, 0], [-1, 0], [2, 0], [-1, -2], [2, 1]],
};

const NO_KICK: Kick = [[0, 0]];

export function kicksFor(piece: TetrisPiece, from: TetrisRotation, to: TetrisRotation): Kick {
  if (piece === 'O') return NO_KICK; // O 는 회전해도 불변, 킥 없음
  const key = `${from}>${to}`;
  return (piece === 'I' ? I_KICKS : JLSTZ_KICKS)[key] ?? NO_KICK;
}
